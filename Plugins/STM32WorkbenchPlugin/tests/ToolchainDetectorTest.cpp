static QString executableName(const QString &name)
{
#ifdef Q_OS_WIN
    return name + ".exe";
#else
    return name;
#endif
}

static QString createExecutable(const QString &directory, const QString &name)
{
    const QString path = QDir(directory).absoluteFilePath(executableName(name));
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly)) return QString();
    file.write("test");
    file.close();
#ifndef Q_OS_WIN
    file.setPermissions(QFile::ReadOwner | QFile::WriteOwner | QFile::ExeOwner |
                        QFile::ReadUser | QFile::WriteUser | QFile::ExeUser);
#endif
    return path;
}

void ToolchainDetectorTest::detectsCompilerAndDebuggerInHintDirectory()
{
    QTemporaryDir temporary(QDir::current().absoluteFilePath("toolchain-test-XXXXXX"));
    QVERIFY(temporary.isValid());
    QVERIFY(!createExecutable(temporary.path(), "arm-none-eabi-gcc").isEmpty());
    QVERIFY(!createExecutable(temporary.path(), "arm-none-eabi-gdb").isEmpty());
    ToolchainDetector detector;
    const ToolchainPaths paths = detector.autoDetect(temporary.path());
    QCOMPARE(QFileInfo(paths.gccPath).absolutePath(), temporary.path());
    QCOMPARE(QFileInfo(paths.gdbPath).absolutePath(), temporary.path());
}

void ToolchainDetectorTest::fillsMissingDebuggerWithoutReplacingSavedCompiler()
{
    QTemporaryDir temporary(QDir::current().absoluteFilePath("toolchain-test-XXXXXX"));
    QVERIFY(temporary.isValid());
    const QString gcc = createExecutable(temporary.path(), "arm-none-eabi-gcc");
    const QString gdb = createExecutable(temporary.path(), "arm-none-eabi-gdb");
    const QString make = createExecutable(temporary.path(), "mingw32-make");
    QVERIFY(!gcc.isEmpty() && !gdb.isEmpty() && !make.isEmpty());
    const QByteArray oldPath = qgetenv("PATH");
    qputenv("PATH", QFile::encodeName(temporary.path()) + QDir::listSeparator().toLatin1() + oldPath);
    QSettings settings(temporary.filePath("tools.ini"), QSettings::IniFormat);
    settings.setValue("STM32Toolchain/gccPath", gcc);
    settings.setValue("STM32Toolchain/makePath", make);
    ToolchainDetector detector;
    const ToolchainPaths paths = detector.loadSettings(&settings);
    qputenv("PATH", oldPath);
    QCOMPARE(paths.gccPath, gcc);
    QCOMPARE(QDir::cleanPath(paths.gdbPath), QDir::cleanPath(gdb));
}

