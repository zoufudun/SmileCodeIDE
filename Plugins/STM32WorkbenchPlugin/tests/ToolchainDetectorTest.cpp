void ToolchainDetectorTest::migratesLegacyLinkerScriptWithBackup()
{
    QTemporaryDir temporary(QDir::current().absoluteFilePath("linker-migration-test-XXXXXX"));
    QVERIFY(temporary.isValid());
    const STM32ChipProfile profile =
        STM32ProfileManager::instance().getProfile("STM32H743VI");
    const QString linkerPath = temporary.filePath(profile.defaultLdFile);
    const QByteArray legacy =
        "/* SmileCodeIDE Auto-Generated Linker Script for STM32H743VI */\n"
        "MEMORY { RAM (xrw) : ORIGIN = 0x20000000, LENGTH = 128K }\n";
    QFile linker(linkerPath);
    QVERIFY(linker.open(QIODevice::WriteOnly));
    QCOMPARE(linker.write(legacy), legacy.size());
    linker.close();

    QString backupPath;
    QString error;
    QVERIFY2(MakefileGenerator::migrateLegacyLinkerScript(
                 temporary.path(), profile, &backupPath, &error), qPrintable(error));
    QVERIFY(!backupPath.isEmpty());
    QFile backup(backupPath);
    QVERIFY(backup.open(QIODevice::ReadOnly));
    QCOMPARE(backup.readAll(), legacy);
    QVERIFY(linker.open(QIODevice::ReadOnly));
    QCOMPARE(QString::fromLatin1(QCryptographicHash::hash(
                 linker.readAll(), QCryptographicHash::Sha256).toHex()),
             profile.linkerSha256);
}

