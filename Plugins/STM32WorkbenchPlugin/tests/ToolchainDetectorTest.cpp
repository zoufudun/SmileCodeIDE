    ToolchainPaths paths;
    paths.gccPath = QFile::decodeName(qgetenv("STM32_WORKBENCH_REAL_GCC"));
    QString error;
    QVERIFY2(MakefileGenerator::generate(project,
        STM32ProfileManager::instance().getProfile("STM32F429IGTx"), paths,
        BuildConfiguration::Debug, {}, {}, {}, &error), qPrintable(error));
    const QString make = QStandardPaths::findExecutable("mingw32-make");
    QVERIFY(!make.isEmpty());
